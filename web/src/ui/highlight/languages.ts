const SUFFIX_SEPARATOR = ".";
const DOT_LENGTH = 1;

export function languageFor(name: string): string | undefined {
  const lower = name.toLowerCase();
  const named = BY_NAME[lower];
  if (named && LANGUAGE_LOADERS[named]) return named;
  for (let at = lower.indexOf(SUFFIX_SEPARATOR); at >= 0; at = lower.indexOf(SUFFIX_SEPARATOR, at + DOT_LENGTH)) {
    const found = BY_SUFFIX[lower.slice(at + DOT_LENGTH)];
    if (found && LANGUAGE_LOADERS[found]) return found;
  }
  return undefined;
}

export function languageLabel(name: string): string {
  const language = languageFor(name);
  return language ? (LANGUAGE_LABELS[language] ?? language) : "Plain text";
}
